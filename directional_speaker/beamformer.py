"""Online null-steering beamformer.

Given (theta_L, theta_R) and two passband (already-modulated) mono streams,
produces an 8-channel output via per-frequency null-steering weights loaded
from an offline LUT.

The LUT is generated by scripts/calibrate_nullsteering.py.
"""
from __future__ import annotations

import json
import math
import pathlib

import numpy as np

from . import config as cfg


class NullSteeringBeamformer:
    """Loads a JSON LUT of per-frequency amplitude/phase weights and applies
    them in the frequency domain to passband signals.
    """

    def __init__(self, lut_path: str | pathlib.Path = cfg.BEAM_LUT_PATH):
        self.lut_path = pathlib.Path(lut_path)
        self._lut: dict[str, dict] = {}
        self.lut_freqs: np.ndarray | None = None
        self._load_lut()

    def _load_lut(self) -> None:
        if not self.lut_path.is_file():
            raise FileNotFoundError(
                f"Beam LUT not found: {self.lut_path}\n"
                f"Run: python scripts/calibrate_nullsteering.py"
            )
        with open(self.lut_path, "r", encoding="utf-8") as f:
            raw = json.load(f)

        # Convert lists back to numpy for fast lookup
        self._lut = {}
        for key, entry in raw.items():
            self._lut[key] = {
                "freqs_hz": np.array(entry["freqs_hz"], dtype=float),
                "amp": np.array(entry["amp"], dtype=float),
                "phase": np.array(entry["phase"], dtype=float),
            }
        # All entries share the same frequency grid; grab from first
        first = next(iter(self._lut.values()))
        self.lut_freqs = first["freqs_hz"]

    @staticmethod
    def _quantize(theta_deg: float) -> int:
        """Round to nearest THETA_STEP_DEG grid point, clipped to [-60, 60]."""
        clipped = float(np.clip(theta_deg, -60.0, 60.0))
        q = int(np.floor(clipped / cfg.THETA_STEP_DEG + 0.5)) * cfg.THETA_STEP_DEG
        return int(np.clip(q, -60, 60))

    def _get_weights(self, target_deg: float, null_deg: float) -> tuple[np.ndarray, np.ndarray]:
        """Return (amp, phase) arrays of shape (n_freqs, N_CHANNELS)."""
        qt = self._quantize(target_deg)
        qn = self._quantize(null_deg)
        key = f"{qt}_{qn}"
        entry = self._lut.get(key)
        if entry is None:
            raise KeyError(
                f"LUT missing entry for target={qt} null={qn} "
                f"(requested target={target_deg:.1f} null={null_deg:.1f}). "
                f"Re-run calibrate_nullsteering.py with required angles."
            )
        return entry["amp"], entry["phase"]

    def apply_passband(self, x: np.ndarray, target_deg: float, null_deg: float) -> np.ndarray:
        """Apply null-steering weights to a single passband signal.

        Parameters
        ----------
        x : np.ndarray
            Real passband signal (already DSB-AM modulated), shape (T,).
        target_deg, null_deg : float
            Steering and null angles in degrees.

        Returns
        -------
        np.ndarray
            8-channel output, shape (N_CHANNELS, T).
        """
        T = x.shape[0]
        X = np.fft.rfft(x)  # (n_fft,)
        freqs_fft = np.fft.rfftfreq(T, 1.0 / cfg.FS_HZ)  # (n_fft,)
        n_fft = len(X)

        amp, phase = self._get_weights(target_deg, null_deg)  # (n_freqs, 8)
        n_freqs = amp.shape[0]

        # Build per-FFT-bin complex weights: (n_fft, N_CHANNELS)
        W = np.ones((n_fft, cfg.N_CHANNELS), dtype=complex)
        half_step = cfg.FREQ_STEP_HZ / 2.0

        for j in range(n_freqs):
            f_c = float(self.lut_freqs[j])
            f_lo = f_c - half_step
            f_hi = f_c + half_step
            mask = (freqs_fft >= f_lo) & (freqs_fft < f_hi)
            if not mask.any():
                continue
            w = amp[j, :] * np.exp(1j * phase[j, :])  # (8,)
            W[mask, :] = w[None, :]

        # Apply weights and inverse FFT
        X_weighted = X[:, None] * W  # (n_fft, 8)
        out = np.fft.irfft(X_weighted, axis=0, n=T)  # (T, 8)
        return out.T.astype(np.float32)  # (8, T)

    def combine(self,
                theta_L_deg: float,
                theta_R_deg: float,
                mod_L: np.ndarray,
                mod_R: np.ndarray) -> np.ndarray:
        """Combine two passband streams into a single 8-channel output.

        mod_L is steered toward theta_L with a null at theta_R;
        mod_R is steered toward theta_R with a null at theta_L.
        The two 8-channel outputs are averaged in the time domain.
        """
        out_L = self.apply_passband(mod_L, theta_L_deg, theta_R_deg)
        out_R = self.apply_passband(mod_R, theta_R_deg, theta_L_deg)
        out = (out_L + out_R) / 2.0
        # Guard against numerical overshoot
        peak = np.max(np.abs(out))
        if peak > 1.0:
            out = out / peak
        return out.astype(np.float32)


