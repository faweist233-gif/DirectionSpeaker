    # Quick smoke test (requires LUT to exist)
    bf = NullSteeringBeamformer()
    t = np.arange(cfg.WINDOW_SAMPLES) / cfg.FS_HZ
    # 1 kHz baseband tone modulated to 40 kHz
    carrier = np.cos(2 * np.pi * cfg.FC_HZ * t)
    mod_tone = 0.5 * (1.0 + 0.5 * np.sin(2 * np.pi * 1000 * t)) * carrier
    y = bf.apply_passband(mod_tone.astype(np.float32), target_deg=0, null_deg=40)
    print(f"apply_passband: in={mod_tone.shape} out={y.shape} max={np.max(np.abs(y)):.3f}")

    y2 = bf.combine(0, 40, mod_tone, mod_tone)
    print(f"combine: out={y2.shape} max={np.max(np.abs(y2)):.3f}")

